    /// <summary>
    /// Add reactions to the message.
    /// </summary>
    /// <param name="emojis">Reactions/emojis to add.</param>
    public async Task AddReactionsAsync(params string[] emojis)
    {
        foreach (var emoji in emojis)
            await Bot._rest.CreateReactionAsync(ChannelId, Id, PartialEmoji.FromString(emoji));
    }
    
    /// <summary>
    /// Remove a reaction.
    /// </summary>
    /// <param name="emoji">Reaction/emoji to remove.</param>
    /// <param name="user">If set, the provide user's reaction will be removed. If <c>null</c>, the bots reaction will be
    /// removed instead.
    /// </param>
    public async Task RemoveReactionAsync(string emoji, User? user = null)
    {
        var pe = PartialEmoji.FromString(emoji);
        if (user is null)
            await Bot._rest.DeleteOwnReactionAsync(ChannelId, Id, pe);
        else
            await Bot._rest.DeleteUserReactionAsync(ChannelId, Id, pe, user);
    }
    
    /// <summary>
    /// Request the users that reacted to the message using the specified emoji.
    /// </summary>
    /// <param name="emoji">The reaction/emoji.</param>
    /// <param name="amount">Amount of users to request (100 max yielded per loop). Can be <c>null</c> to request
    /// <b>all</b> users, and depending on the amount of reacts it can take a while.
    /// </param>
    /// <param name="after">Request users whose accounts were created after the given date.</param>
    /// <param name="type">Type of reaction.</param>
    /// <returns>The requested amount of users.</returns>
    public async IAsyncEnumerable<ICollection<User>> UsersForReactionAsync(string emoji, int? amount = 100,
        DateTime? after = null,
        ReactionType type = ReactionType.Normal)
    {
        const int indefinite = -1;
        var remaining = amount ?? indefinite;

        var afterSnowflakeTime = after is not null ? Util.DateTimeToSnowflake(after.Value) : 0;
        var hasMore = true;
        var yielded = new List<User>();

        do
        {
            yielded.Clear();
            var requestAmount = remaining == indefinite ? 100 : Math.Min(remaining, 100);
            var users = await Bot._rest.GetReactionsAsync(ChannelId, Id, PartialEmoji.FromString(emoji), type,
                requestAmount, afterSnowflakeTime);
            if (users.Count < 100)
                hasMore = false;

            foreach (var user in users)
            {
                yielded.Add(user);
                if (remaining == indefinite) continue;

                remaining -= 1;
                if (remaining == 0)
                    hasMore = false;
            }

            afterSnowflakeTime = users.Last().Id;
            yield return yielded;
        } while (hasMore);
    }

    /// <summary>
    /// Removes all reactions.
    /// </summary>
    /// <param name="emoji">If set, removes all specified reactions/emojis.</param>
    public async Task RemoveAllReactionsAsync(string? emoji = null)
    {
        if (emoji is null)
            await Bot._rest.DeleteAllReactions(ChannelId, Id);
        else
            await Bot._rest.DeleteAllReactionsForEmoji(ChannelId, Id, PartialEmoji.FromString(emoji));
    }

    /// <summary>
    /// Retrieve a reaction on the message.
    /// </summary>
    /// <param name="emoji">The emoji that represents the reaction.</param>
    /// <returns>The reaction matching the provided emoji, or <c>null</c> if not found.</returns>
    /// <remarks>This will always be <c>null</c> if not used on a cached message. Meaning if used on a message that was sent and
    /// the message object is returned from that method, this will be <c>null</c>. Only when retrieved from the cache will this
    /// have a value. Example:
    /// <code>
    ///     var sent = await message.Channel.SendAsync("discord.cs");
    ///     await sent.AddReactionAsync("😎");
    ///     var reaction1 = sent.GetReaction("😎"); // Will be null
    ///
    ///
    /// 
    ///     var cached = bot.GetMessage(sent.Id);
    ///     var reaction2 = cached.GetReaction("😎"); // Contains the reaction
    /// </code>
    /// </remarks>
    public Reaction? GetReaction(string emoji)
    {
        var pe = PartialEmoji.FromString(emoji);
        if (_reactions.FirstOrDefault(r => r.Emoji.Equals(pe)) is { } reaction)
            return reaction;
        return null;
    }

    /// <summary>
    /// Reply to a message.
    /// </summary>
    /// <param name="content">Content of the message.</param>
    /// <param name="silent">If <c>true</c>, mentions will not provide a desktop or push notification.</param>
    /// <param name="tts">Whether this is a TTS message.</param>
    /// <param name="embeds">Embeds (max 10), up to 6000 characters total.</param>
    /// <param name="allowedMentions">Allowed mentions for the message.</param>
    /// <param name="stickers">Up to 3 stickers to send in the message.</param>
    /// <param name="poll">A poll.</param>
    /// <param name="files">Files to upload with the message.</param>
    /// <param name="suppressEmbeds">Whether embeds are suppressed.</param>
    /// <returns>The message that was sent.</returns>
    public async Task<Message> ReplyAsync(string? content = null, bool silent = false, bool tts = false,
        IEnumerable<Embed>? embeds = null,
        AllowedMentions? allowedMentions = null, IEnumerable<GuildSticker>? stickers = null, Poll? poll = null,
        ICollection<DFile>? files = null, bool suppressEmbeds = false) =>
        await ChannelServicer.SendAsync(Channel, content, silent, tts, embeds, allowedMentions, stickers, poll, files,
            ToReference(), suppressEmbeds);

    /// <summary>
    /// Edit the message.
    /// </summary>
    /// <param name="edit">A message edit instance.</param>
    /// <returns>The edited message.</returns>
    public async Task<Message> EditAsync(MessageEdit edit) =>
        await Bot._rest.EditMessage(ChannelId, Id, edit);
    
    /// <summary>
    /// Delete the message.
    /// </summary>
    /// <param name="after">Amount of time in <b>seconds</b> to wait before deleting the message.</param>
    /// <param name="reason">Reason for deleting the message. This is displayed in the audit-log.</param>
    /// <returns>The task. If <paramref name="after"/> is provided, the task can be started in the background and either
    /// be discarded or awaited to produce any errors.
    /// <code>
    ///     // await like normal
    ///     await message.DeleteAsync(5);
    ///
    /// 
    ///     var task = message.DeleteAsync(5);
    ///     // Continue and process other information...
    ///     // If you want to know about any errors, await it
    ///     await task;
    ///
    /// 
    ///     // Or fire and forget, discarding any errors
    ///     _ = message.DeleteAsync(5);
    /// </code>
    /// </returns>
    /// <remarks>Requires <see cref="Permission.ManageMessages"/>.</remarks>
    public Task DeleteAsync(int? after = null, string? reason = null)
    {
        if (after == null)
            return Bot._rest.DeleteMessageAsync(ChannelId, Id, reason);
        return Task.Run(async () =>
        {
            await Task.Delay(TimeSpan.FromSeconds(after.Value));
            await Bot._rest.DeleteMessageAsync(ChannelId, Id, reason);
        });
    }
    
    /// <summary>
    /// Publish the message to all following channels.
    /// </summary>
    /// <remarks>Requires <see cref="Permission.SendMessages"/>.</remarks>
    public async Task PublishAsync() =>
        await Bot._rest.CrosspostMessageAsync(ChannelId, Id);
    
    /// <summary>
    /// Create a thread from a message.
    /// </summary>
    /// <param name="name">Name of the thread (1-100 characters).</param>
    /// <param name="duration">When the thread will stop showing in the channel list after inactivity.</param>
    /// <param name="slowModeDelaySeconds">Amount of seconds a user has to wait before sending another message (1-21600),
    /// or <c>null</c> to disable it.
    /// </param>
    /// <param name="reason">Reason for creating the thread. This is displayed in the audit-log.</param>
    /// <returns>The created thread.</returns>
    /// <remarks>Only valid for messages that were created in a <see cref="TextChannel"/> or <see cref="AnnouncementChannel"/>.</remarks>
    public async Task<ThreadChannel> CreateThreadAsync(string name,
        ThreadArchiveDuration duration = ThreadArchiveDuration.ThreeDays, int? slowModeDelaySeconds = null,
        string? reason = null)
    {
        var payload = new JSON
        {
            { "name", name },
            { "auto_archive_duration", duration },
            { "rate_limit_per_user", slowModeDelaySeconds ?? 0 }
        };
        return await Bot._rest.StartThreadFromMessage(Guild!, ChannelId, Id, payload, reason);
    }

    private MessageReference ToReference() => 
        new (MessageReferenceType.Default, Id, ChannelId, GuildId, false);
}

/// <summary>
/// Represents the values that can be edited for a <see cref="Message"/>.
/// </summary>
public struct MessageEdit
{
    internal readonly JSON _payload = [];
    internal IEnumerable<DFile> _files = [];
    
    /// <summary>
    /// Initialize a new message edit instance.
    /// </summary>
    public MessageEdit() { }

    /// <summary>
    /// Set the message content.
    /// </summary>
    /// <param name="content"></param>
    /// <returns>The message edit instance.</returns>
    public MessageEdit SetContent(string content)
    {
        _payload["content"] = content;
        return this;
    }

    /// <summary>
    /// Set the embeds.
    /// </summary>
    /// <param name="embeds">Embeds to set.</param>
    /// <returns>The message edit instance.</returns>
    public MessageEdit SetEmbeds(IEnumerable<Embed> embeds)
    {
        _payload["embeds"] = embeds;
        return this;
    }

    /// <summary>
    /// Set attachments and or files.
    /// </summary>
    /// <param name="attachments">Any attachments you would like retained.</param>
    /// <param name="files">New files that will be attached.</param>
    /// <returns>The message edit instance.</returns>
    /// <remarks>
    /// Both <paramref name="attachments"/> and <paramref name="files"/> can be <c>null</c> to remove all attachments
    /// </remarks>
    public MessageEdit SetAttachments(IReadOnlyCollection<MessageAttachment>? attachments, IEnumerable<DFile>? files)
    {
        _payload["attachments"] = attachments ?? [];
        _files = files ?? [];
        return this;
    }

    /// <summary>
    /// Set whether embeds are suppressed.
    /// </summary>
    /// <param name="suppressed">If embeds are suppressed.</param>
    /// <returns>The message edit instance.</returns>
    public MessageEdit SetSuppressEmbeds(bool suppressed)
    {
        if (suppressed)
            _payload["flags"] = Util.FromFlags([MessageFlag.SuppressEmbeds]);
        else
            _payload["flags"] = 0;
        return this;
    }

    /// <summary>
    /// Set allowed mentions.
    /// </summary>
    /// <param name="allowedMentions">An allowed mentions object.</param>
    /// <returns>The message edit instance.</returns>
    public MessageEdit SetAllowedMentions(AllowedMentions? allowedMentions)
    {
        _payload["allowed_mentions"] = allowedMentions?.ToJson();
        return this;
    }
}

