/// <summary>
/// Represents what mentions are allowed in a <see cref="Message"/>.
/// </summary>
public record struct AllowedMentions
{
    // DOCS: https://discord.com/developers/docs/resources/message#allowed-mentions-object
    
    /// <summary>
    /// If users can be mentioned in a message.
    /// </summary>
    public bool Users { get; set; }

    /// <summary>
    /// If roles can be mentioned in a message.
    /// </summary>
    public bool Roles { get; set; }

    /// <summary>
    /// If the user to the message that is being replied to are allowed to be mentioned in a message.
    /// </summary>
    public bool RepliedUser { get; set; }

    /// <summary>
    /// If <c>@everyone</c> or <c>@here</c> are allowed to be mentioned in a message.
    /// </summary>
    public bool Everyone { get; set; }

    /// <summary>
    /// The <b>only</b> users that can be mentioned in a message.
    /// </summary>
    public HashSet<User> ExemptUsers { get; set; } = [];

    /// <summary>
    /// The <b>only</b> roles that can be mentioned in a message.
    /// </summary>
    public HashSet<Role> ExemptRoles { get; set; } = [];

    /// <summary>
    /// Initializes a new allowed mentions instance with its fields set to the equivalent of <see cref="AllowedMentions.Default"/>.
    /// </summary>
    public AllowedMentions()
    {
        Users = true;
        Roles = false;
        RepliedUser = true;
        Everyone = false;
    }

    /// <summary>
    /// Initializes a new allowed mentions instance.
    /// </summary>
    /// <param name="users">If users can be mentioned in a message.</param>
    /// <param name="roles">If roles can be mentioned in a message.</param>
    /// <param name="repliedUser">If the user to the message that is being replied to are allowed to be mentioned in a message.</param>
    /// <param name="everyone">If <c>@everyone</c> or <c>@here</c> are allowed to be mentioned in a message.</param>
    public AllowedMentions(bool users, bool roles, bool repliedUser, bool everyone)
    {
        Users = users;
        Roles = roles;
        RepliedUser = repliedUser;
        Everyone = everyone;
    }

    /// <summary>
    /// Returns an <see cref="AllowedMentions"/> with all of its fields set to <c>true</c>.
    /// </summary>
    public static readonly AllowedMentions All = new(users: true, roles: true, repliedUser: true, everyone: true);

    /// <summary>
    /// Returns an <see cref="AllowedMentions"/> with its fields set to:
    /// <list type="bullet">
    ///     <item><c>Users = true</c></item>
    ///     <item><c>Roles = false</c></item>
    ///     <item><c>RepliedUser = true</c></item>
    ///     <item><c>Everyone = false</c></item>
    /// </list>
    /// </summary>
    public static readonly AllowedMentions Default = new();

    /// <summary>
    /// Returns an <see cref="AllowedMentions"/> with all of its fields set to <c>false</c>.
    /// </summary>
    public static readonly AllowedMentions None = new(users: false, roles: false, repliedUser: false, everyone: false);

    internal JSON ToJson()
    {
        var parse = new List<string>();

        if (Users)
            parse.Add("users");
        if (Roles)
            parse.Add("roles");
        if (Everyone)
            parse.Add("everyone");

        // "users" & "roles" must be removed or else an invalidation error will occur because of mutual exclusivity.
        if (ExemptUsers.Count == 0 && Users)
            parse.Remove("users");
        if (ExemptRoles.Count == 0 && Roles)
            parse.Remove("roles");

        var roleQuery =
            from role in ExemptRoles
            select role.Id.ToString();
        var userQuery = 
            from user in ExemptUsers
            select user.Id.ToString();

        return new JSON
        {
            { "parse", parse },
            { "roles", roleQuery },
            { "users", userQuery },
            { "replied_user", RepliedUser }
        };
    }
}

/// <summary>
/// Represents a poll on a <see cref="Message"/>.
/// </summary>
public record Poll
{
    // DOCS: https://discord.com/developers/docs/resources/poll#poll-object-poll-object-structure
    
    /// <summary>
    /// The question of the poll.
    /// </summary>
    [JsonIgnore]
    public string Question
    {
        get => _question.Text!;
        set => _question.Text = value;
    }
    [JsonProperty("question")] private readonly PollMedia _question;

    /// <summary>
    /// Each of the answers available in the poll, up to 10.
    /// </summary>
    [JsonProperty("answers")]
    public List<PollAnswer> Answers { get; set; }

    /// <summary>
    /// When the poll ends.
    /// </summary>
    [JsonProperty("expiry")]
    public DateTime? Expires { get; init; }
    [JsonProperty("duration")] internal int _duration;

    /// <summary>
    /// Whether a user can select multiple answers.
    /// </summary>
    [JsonProperty("allow_multiselect")]
    public bool IsMultiselectAllowed { get; set; }

    /// <summary>
    /// The layout type of the poll.
    /// </summary>
    [JsonProperty("layout_type")]
    public PollLayout Layout { get; set; }

    /// <summary>
    /// The results of the poll.
    /// </summary>
    [JsonProperty("results")]
    public PollResults? Results { get; init; }

    #region CUSTOM

    /// <summary>
    /// Your bot instance.
    /// </summary>
    public Bot Bot { get; internal set; } = null!;

    /// <summary>
    /// Message the poll is attached to.
    /// </summary>
    public Message Message { get; internal set; } = null!;
    
    #endregion
    
    /// <summary>
    /// Initializes a new poll instance.
    /// </summary>
    /// <param name="question">The question of the poll.</param>
    /// <param name="answers">Each of the answers available in the poll, up to 10.</param>
    /// <param name="expires">When the poll will close. 1 hour minimum, 32 days maximum.</param>
    /// <param name="allowMultiselect">Whether a user can select multiple answers.</param>
    /// <param name="layout">The layout type of the poll.</param>
    public Poll(string question, IEnumerable<PollAnswer> answers, TimeSpan expires, bool allowMultiselect = false,
        PollLayout layout = PollLayout.Default)
    {
        _question = new PollMedia(question);
        Question = _question.Text!;
        Answers = answers.ToList();
        _duration = GetDuration(expires);
        IsMultiselectAllowed = allowMultiselect;
        Layout = layout;
    }

    /// <summary>
    /// A more simple way to initialize a new poll instance. By default, <see cref="IsMultiselectAllowed"/> is <c>false</c>
    /// and <see cref="Layout"/> is <see cref="PollLayout.Default"/>.
    /// </summary>
    /// <param name="question">The question of the poll.</param>
    /// <param name="answers">Each of the answers available in the poll as a simple string, up to 10.</param>
    /// <param name="expires">When the poll will close. 1 hour minimum, 32 days maximum.</param>
    public Poll(string question, IEnumerable<string> answers, TimeSpan expires)
    {
        _question = new PollMedia(question);
        Question = _question.Text!;
        Answers = answers.Select(ans => new PollAnswer(new PollMedia(ans))).ToList();
        _duration = GetDuration(expires);
        IsMultiselectAllowed = false;
        Layout = PollLayout.Default;
    }

    [JsonConstructor]
    internal Poll(PollMedia question, List<PollAnswer> answers)
    {
        _question = question;
        Answers = answers;
    }
    
    /// <summary>
    /// Retrieve an answer.
    /// </summary>
    /// <param name="id">Answer ID.</param>
    /// <returns>The answer matching the provided ID, or <c>null</c> if not found.</returns>
    public PollAnswer? GetAnswer(int id) => 
        Answers.FirstOrDefault(a => a.Id == id);
    
    /// <summary>
    /// Users that voted for the provided answer.
    /// </summary>
    /// <param name="answer">Answer to check.</param>
    /// <param name="amount">Amount of users to return, max 100 per iteration.</param>
    /// <param name="after">Retrieve users after the provided date.</param>
    /// <returns>The requested amount of voters (users).</returns>
    public async IAsyncEnumerable<ICollection<User>> VotersAsync(PollAnswer answer, int? amount = 100, DateTime? after = null)
    {
        const int indefinite = -1;
        var remaining = amount ?? indefinite;
    
        var afterSnowflakeTime = after is not null ? Util.DateTimeToSnowflake(after.Value) : 0;
        var hasMore = true;
        var yielded = new List<User>();
    
        do
        {
            yielded.Clear();
            var requestAmount = remaining == indefinite ? 100 : Math.Min(remaining, 100);
            var users = await Bot._rest.GetAnswerVotersAsync(Message.ChannelId, Message.Id, answer.Id!.Value,
                afterSnowflakeTime, requestAmount);
            if (users.Count < 100)
                hasMore = false;
    
            foreach (var user in users)
            {
                yielded.Add(user);
                if (remaining == indefinite) continue;
    
                remaining -= 1;
                if (remaining == 0)
                    hasMore = false;
            }

            if (users.Count > 0)
            {
                afterSnowflakeTime = users.Last().Id;
                yield return yielded;
            }
            else
                yield break;
        } while (hasMore);
    }
    
    /// <summary>
    /// End the poll. You cannot end polls from other users.
    /// </summary>
    /// <returns>Message that the poll was attached to.</returns>
    public async Task<Message> EndAsync() => 
        await Bot._rest.EndPollAsync(Message.ChannelId, Message.Id);

    private static int GetDuration(TimeSpan expires)
    {
        var now = DateTimeOffset.UtcNow;
        var future = now.Add(expires);
        return (int)(future - now).TotalHours;
    }
}

